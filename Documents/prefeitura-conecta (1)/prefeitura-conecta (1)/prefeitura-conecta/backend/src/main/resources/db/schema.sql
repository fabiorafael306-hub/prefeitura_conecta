-- Para bancos JÁ criados com a versão anterior, execute também db/migracao-001-autenticacao.sql
-- (este arquivo é idempotente, mas CREATE TABLE IF NOT EXISTS não adiciona colunas a tabelas existentes).

CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 cpf VARCHAR(11) NOT NULL UNIQUE,
 endereco VARCHAR(250),
 tipo_usuario VARCHAR(20) NOT NULL DEFAULT 'CIDADAO',
 -- Hash BCrypt da senha (nunca texto puro). Nulo apenas para cadastros anteriores à autenticação.
 senha_hash VARCHAR(100),
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias_problema (
 id BIGINT PRIMARY KEY,
 codigo_area VARCHAR(50) NOT NULL,
 nome_area VARCHAR(100) NOT NULL,
 codigo_tipo VARCHAR(70) NOT NULL,
 nome_tipo VARCHAR(120) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_categoria_codigo UNIQUE(codigo_area,codigo_tipo)
);

CREATE TABLE IF NOT EXISTS reclamacoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 categoria_id BIGINT NOT NULL REFERENCES categorias_problema(id),
 descricao TEXT NOT NULL,
 endereco VARCHAR(250) NOT NULL,
 criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS protocolos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(40) NOT NULL UNIQUE,
 reclamacao_id BIGINT NOT NULL UNIQUE REFERENCES reclamacoes(id),
 status VARCHAR(20) NOT NULL DEFAULT 'EM_ANALISE'
   CHECK (status IN ('EM_ANALISE','EM_ABERTO','CONCLUIDO')),
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reclamacoes_usuario ON reclamacoes(usuario_id);
CREATE INDEX IF NOT EXISTS idx_reclamacoes_categoria ON reclamacoes(categoria_id);
CREATE INDEX IF NOT EXISTS idx_protocolos_reclamacao ON protocolos(reclamacao_id);
CREATE INDEX IF NOT EXISTS idx_protocolos_codigo ON protocolos(codigo);

